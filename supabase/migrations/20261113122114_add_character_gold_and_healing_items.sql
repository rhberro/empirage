create table public.healing_items (
  id smallint generated by default as identity primary key,
  slug text not null unique,
  name text not null unique,
  healing_amount integer not null check (healing_amount > 0),
  gold_cost bigint not null check (gold_cost > 0)
);

insert into public.healing_items (id, slug, name, healing_amount, gold_cost)
values
  (1, 'potion', 'Potion', 20, 10),
  (2, 'super-potion', 'Super Potion', 50, 25),
  (3, 'hyper-potion', 'Hyper Potion', 200, 75),
  (4, 'max-potion', 'Max Potion', 9_999, 150);

alter table public.characters
  add column gold bigint not null default 100,
  add column healing_item_id smallint references public.healing_items (id),
  add column healing_threshold_percentage smallint,
  add constraint characters_gold_nonnegative check (gold >= 0),
  add constraint characters_healing_configuration_check check (
    (healing_item_id is null and healing_threshold_percentage is null)
    or (
      healing_item_id is not null
      and healing_threshold_percentage between 1 and 100
    )
  );

alter table public.healing_items enable row level security;

revoke all on table public.healing_items from anon, authenticated;

grant select on table public.healing_items to authenticated;

create policy "Authenticated users can view healing items"
on public.healing_items
for select
to authenticated
using (true);

create function public.use_character_healing_item(
  target_character_id uuid,
  target_item_id smallint
)
returns table (gold bigint, healing_amount integer)
language plpgsql
security definer
set search_path = ''
as $$
begin
  return query
  update public.characters as characters
  set gold = characters.gold - items.gold_cost
  from public.healing_items as items
  where characters.id = target_character_id
    and characters.healing_item_id = target_item_id
    and items.id = target_item_id
    and characters.gold >= items.gold_cost
  returning characters.gold, items.healing_amount;
end;
$$;

revoke all on function public.use_character_healing_item(uuid, smallint)
from public, anon, authenticated;

grant execute on function public.use_character_healing_item(uuid, smallint)
to service_role;
